/**
 * Look up a prompt by ID.
 */
export function getPromptById(id: string): RareAnswerPrompt | undefined {
  return RARE_ANSWER_PROMPTS.find((p) => p.id === id);
}

/**
 * Return random selection of distinct prompts for a game session.
 */
export function getRandomSessionPrompts(
  count = 5,
  rng: () => number = Math.random
): RareAnswerPrompt[] {
  const pool = [...RARE_ANSWER_PROMPTS];
  // Fisher-Yates shuffle
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, Math.min(count, pool.length));
}
